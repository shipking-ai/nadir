// Generates docs/LICENSE-INVENTORY.md from package-lock.json + each installed package's package.json.
// Production (non-dev) dependencies are listed separately from development-only ones.
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const lock = JSON.parse(fs.readFileSync(path.join(root, 'package-lock.json'), 'utf8'));
const rows = [];
for (const [p, meta] of Object.entries(lock.packages)) {
  if (!p) continue;
  const name = p.replace(/^.*node_modules\//, '');
  let license = meta.license;
  let homepage = '';
  try {
    const pj = JSON.parse(fs.readFileSync(path.join(root, p, 'package.json'), 'utf8'));
    license = pj.license || (pj.licenses && pj.licenses.map((l) => l.type).join(' OR ')) || license;
    homepage = (typeof pj.repository === 'string' ? pj.repository : pj.repository?.url) || pj.homepage || '';
  } catch { /* optional dep not installed on this platform */ }
  rows.push({ name, version: meta.version, license: typeof license === 'object' ? JSON.stringify(license) : license || 'UNKNOWN', dev: !!meta.dev, optional: !!meta.optional, homepage: homepage.replace(/^git\+/, '').replace(/\.git$/, '') });
}
rows.sort((a, b) => a.name.localeCompare(b.name));
const group = (list) => list.reduce((m, r) => ((m[r.license] ||= []).push(r), m), {});
const table = (list) => ['| Package | Version | License | Source |', '|---|---|---|---|', ...list.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.homepage || ''} |`)].join('\n');
const prod = rows.filter((r) => !r.dev);
const dev = rows.filter((r) => r.dev);
const summary = (list) => Object.entries(group(list)).sort((a, b) => b[1].length - a[1].length).map(([l, v]) => `- **${l}**: ${v.length}`).join('\n');

const out = `# Dependency licence inventory

Generated by \`node scripts/license-inventory.js\` on ${new Date().toISOString().slice(0, 10)} from \`package-lock.json\` and installed \`package.json\` files. Licence strings are what each package *declares*; they have not been verified against the full licence text of each file. This is an engineering inventory, **not legal advice**.

## Production dependencies (${prod.length}) — shipped inside Nadir

${summary(prod)}

${table(prod)}

## Development-only dependencies (${dev.length}) — not shipped

${summary(dev)}

${table(dev)}
`;
fs.writeFileSync(path.join(root, 'docs', 'LICENSE-INVENTORY.md'), out);
const unknown = rows.filter((r) => /UNKNOWN|UNLICENSED/i.test(r.license));
console.log(`prod=${prod.length} dev=${dev.length} unknown=${unknown.length}`, unknown.map((u) => u.name).join(', '));
// CI gate: a shipped (production) dependency with an unknown or missing licence fails the build.
if (unknown.some((u) => prod.includes(u))) { console.error('FAIL: production dependency with UNKNOWN/UNLICENSED licence'); process.exitCode = 1; }
const copyleft = prod.filter((r) => /GPL|AGPL|LGPL|MPL|EPL|CC-BY-SA/i.test(r.license));
console.log('copyleft/weak-copyleft in prod:', copyleft.map((r) => `${r.name}@${r.version} (${r.license})`).join(', ') || 'none');
